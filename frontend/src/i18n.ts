const catalogs: Record<string, Record<MessageKey, string>> = { en, tr };

export type Translate = (key: MessageKey, vars?: Record<string, string>) => string;

export function translator(language: string): Translate {
  const catalog = catalogs[language.split("-")[0] ?? "en"] ?? en;
  return (key, vars) => {
    let text = catalog[key] ?? en[key];
    for (const [name, value] of Object.entries(vars ?? {})) {
      text = text.replace(`{${name}}`, value);
    }
    return text;
  };
}

export function hasMessage(key: string): key is MessageKey {
  return key in en;
}

/** Translate a source enum value (e.g. "BALANCED", "Detraining"); null when unknown. */
export function categoryMessage(value: string): MessageKey | null {
  const key = `cat_${value.trim().toLowerCase().replace(/[\s-]+/g, "_")}`;
  return hasMessage(key) ? key : null;
}

/** Readable sport name; unknown source sport keys are humanized ("e_bike_fitness" → "E bike fitness"). */
export function sportLabel(t: Translate, sport: string): string {
  const key = `sport_${sport}`;
  if (hasMessage(key)) return t(key);
  const words = sport.replace(/_/g, " ").trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}
